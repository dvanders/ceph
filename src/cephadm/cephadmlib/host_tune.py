"""Fix what host-precheck reports: power management, sysctls and tools.

Runtime settings (CPU governor and energy preference, deep C-states, PCIe
ASPM, NVMe APST, THP, NIC Energy-Efficient Ethernet) are written by one
generated shell script. The same script runs at boot from the
ceph-host-tune systemd unit, so what is applied now and what is applied
after a reboot cannot drift apart. I/O schedulers are set by a udev rule,
so hot-plugged disks get them too, and NUMA sysctls by a sysctl.d file.

Kernel command line arguments are only changed with cmdline=True: through
grubby on RHEL-family hosts, or else by adding them to GRUB_CMDLINE_LINUX in
/etc/default/grub and regenerating the grub configuration (Debian, Ubuntu,
SUSE). They take effect at the next reboot, which is left to the operator.

Missing tools that host-precheck and burnin use (smartmontools, nvme-cli,
ethtool, tuned, irqbalance, ipmitool on hosts with a BMC, stress-ng,
iperf3) are installed one by one with the distribution's package manager,
so one unavailable package does not stop the others; repositories are
never added. tuned and irqbalance are enabled.

The default is a dry run that shows what would change.
"""

